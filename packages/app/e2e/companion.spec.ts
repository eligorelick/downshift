import { expect, test } from '@playwright/test'
import { advance, freshPage, go, startDemo } from './helpers'

test('companion starts without a focus block and Stop removes its running state', async ({ page }) => {
  await freshPage(page)
  await page.getByRole('button', { name: 'Got it', exact: true }).click()
  const companion = page.getByRole('region', { name: 'Heart rate companion' })
  await expect(companion.getByText('Companion stopped', { exact: true })).toBeVisible()
  await companion.getByRole('button', { name: 'Start companion', exact: true }).click()
  await expect(companion.locator(':focus')).toHaveCount(1)
  await expect(companion.getByText('Waiting for a heart rate device', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Stop companion', exact: true })).toBeVisible()
  await go(page, 'focus')
  await expect(page.getByRole('button', { name: 'Start studying', exact: true })).toBeVisible()
  await go(page, 'home')
  await page.getByRole('button', { name: 'Stop companion', exact: true }).click()
  await expect(companion.locator(':focus')).toHaveCount(1)
  await page.reload()
  await expect(companion.getByText('Companion stopped', { exact: true })).toBeVisible()
  await expect(companion.getByRole('button', { name: 'Snooze 15 minutes' })).toHaveCount(0)
})

test('passive demo learns, checks in and offers existing breathing without logging focus blocks', async ({
  page,
}) => {
  await freshPage(page)
  await startDemo(page, 'stress-rise')
  await go(page, 'home')
  await page.getByRole('button', { name: 'Start companion', exact: true }).click()
  await expect(page.getByText('Learning your baseline', { exact: true })).toBeVisible()
  for (let i = 0; i < 45; i++) await advance(page, 60, 60, 250)
  await page.waitForTimeout(2500)
  await expect(page.getByRole('heading', { name: 'Feeling tense?' })).toBeVisible()
  await expect(page.getByText('Watching your heart rate', { exact: true })).toBeVisible()
  await expect(page.getByText('Completed minute', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Breathe', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Begin', exact: true })).toBeVisible()
  await expect(page.getByText(/Stop if you feel dizzy/)).toBeVisible()
  await go(page, 'history')
  await expect(page.locator('.history-type').getByText('Focus', { exact: true })).toHaveCount(0)
  await expect(page.locator('.history-type').getByText('Breathe', { exact: true })).toHaveCount(0)
  await expect(page.locator('.history-type').getByText('Nudge', { exact: true })).toHaveCount(1)
})

test('snooze survives reload, Resume learns again and workout suppresses the companion', async ({ page }) => {
  await freshPage(page)
  await startDemo(page, 'resting')
  await go(page, 'home')
  await page.getByRole('button', { name: 'Start companion', exact: true }).click()
  await page.getByRole('button', { name: 'Snooze 15 minutes', exact: true }).click()
  await expect(page.getByText('Snoozed', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Snoozed', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Resume companion', exact: true }).click()
  await expect(page.getByText('Waiting for a heart rate device', { exact: true })).toBeVisible()
  await startDemo(page, 'resting')
  await go(page, 'workout')
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await go(page, 'home')
  await expect(page.getByText('Paused during workout', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Feeling tense?' })).toHaveCount(0)
})
